"""Generate firmware/LedLetters/glyph_data.h: the glyph catalog for the firmware.

Reads led_map.json from the glyph design files (the 3D model project). For every glyph it holds the
planned LED count, the size and the strip pieces ("steps") in wiring order, from the input (IN) to
the output (OUT). Each step becomes one segment; its points are the LED centres in data order, so at
the planned count every LED sits exactly where it is in the glyph. If a user enters a different LED
count in the app, the firmware spreads the LEDs along the same path.

Units: mm, x right, y up, origin at the glyph's bottom-left.

Usage: python3 tools/gen_glyphs.py <folder with led_map.json>
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'firmware', 'LedLetters', 'glyph_data.h')
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'led-letters')

PULSES = {'Heart', 'Amp'}   # glyphs that beat in the Heartbeat effect


def main():
    path = os.path.join(SRC, 'led_map.json')
    if not os.path.exists(path):
        sys.exit('led_map.json not found in %s\nUsage: python3 tools/gen_glyphs.py <folder with led_map.json>' % SRC)
    glyphs = json.load(open(path, encoding='utf-8'))['glyphs']

    pts, segs, defs, problems = [], [], [], []
    for label, g in glyphs.items():
        name, steps = g['name'], g['steps']
        if sum(s['leds'] for s in steps) != g['leds']:
            problems.append('%s: steps add up to %d, glyph says %d' % (name, sum(s['leds'] for s in steps), g['leds']))
        if g['leds'] > 255 or len(steps) > 255:
            problems.append('%s: too many LEDs or steps for the firmware tables' % name)
        first_seg = len(segs)
        for s in steps:
            xy = s['leds_xy']
            if len(xy) != s['leds']:
                problems.append('%s step %s: %d LED positions for %d LEDs' % (name, s['step'], len(xy), s['leds']))
            segs.append((s['leds'], len(xy), len(pts)))
            pts.extend((round(x), round(y)) for x, y in xy)
        defs.append((name, label, g['leds'], round(g['width_mm']), round(g['height_mm']),
                     name in PULSES, first_seg, len(steps)))
    if problems:
        sys.exit('led_map.json is inconsistent:\n  ' + '\n  '.join(problems))

    L = ['// Generated by tools/gen_glyphs.py from the glyph design files (led_map.json) - do not edit by hand.',
         '#pragma once', '#include <stdint.h>', '',
         '// One segment per strip piece, in wiring order (IN -> OUT).',
         'struct GlyphSeg { uint8_t leds; uint8_t numPts; uint16_t firstPt; };',
         'struct GlyphDef { const char* name; const char* label; uint8_t leds; uint16_t widthMm, heightMm;',
         '                  bool pulses; uint16_t firstSeg; uint8_t numSegs; };', '',
         '// LED centres in mm (x right, y up, origin bottom-left of the glyph), in data order',
         'static const int16_t GLYPH_PTS[][2] = {']
    for i in range(0, len(pts), 10):
        L.append('  ' + ' '.join('{%d,%d},' % p for p in pts[i:i + 10]))
    L += ['};', '', 'static const GlyphSeg GLYPH_SEGS[] = {']
    for i in range(0, len(segs), 6):
        L.append('  ' + ' '.join('{%d,%d,%d},' % s for s in segs[i:i + 6]))
    L += ['};', '', 'static const GlyphDef GLYPHS[] = {']
    for name, label, total, w, h, pulses, s0, ns in defs:
        L.append('  {"%s", "%s", %d, %d, %d, %s, %d, %d},' % (name, label, total, w, h,
                                                              'true' if pulses else 'false', s0, ns))
    L += ['};', 'static const uint8_t GLYPH_COUNT = sizeof(GLYPHS) / sizeof(GLYPHS[0]);', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(L))

    for name, label, total, w, h, pulses, s0, ns in defs:
        print('%-6s %3d LEDs  steps %s' % (name, total, ','.join(str(segs[i][0]) for i in range(s0, s0 + ns))))
    print('%d glyphs, %d LEDs, %d segments -> %s' % (len(defs), sum(d[2] for d in defs), len(segs),
                                                     os.path.normpath(OUT)))


if __name__ == '__main__':
    main()
